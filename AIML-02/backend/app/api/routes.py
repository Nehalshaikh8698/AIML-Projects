def _media_url(filename: str) -> str:
    return f"/media/{filename}"


def _demo_analysis(image: Image.Image, threshold: float) -> dict:
    """Clearly-labelled illustrative output for UI/workflow demonstrations only."""
    gray = np.asarray(image.convert("L").resize((224, 224)), dtype=np.float32) / 255.0
    # A deterministic image-statistics illustration, NOT a trained medical model.
    contrast = float(np.std(gray))
    brightness = float(np.mean(gray))
    edge = np.abs(np.diff(gray, axis=0)).mean() + np.abs(np.diff(gray, axis=1)).mean()
    seed = int((contrast * 1e6 + brightness * 1e5 + edge * 1e6)) % (2**32)
    rng = np.random.default_rng(seed)
    raw = rng.random((28, 28), dtype=np.float32)
    raw = np.asarray(Image.fromarray((raw * 255).astype(np.uint8)).resize((224, 224), Image.Resampling.BILINEAR), dtype=np.float32) / 255.0
    # Gently modulate by local contrast to make a reproducible visual texture.
    local = np.asarray(Image.fromarray((gray * 255).astype(np.uint8)).filter(ImageFilter.FIND_EDGES), dtype=np.float32) / 255.0
    cam = np.clip(0.65 * raw + 0.35 * local, 0, 1)
    r = np.clip(1.5 * cam, 0, 1)
    g = np.clip(1.5 - np.abs(2 * cam - 1) * 1.5, 0, 1)
    b = np.clip(1.0 - 1.5 * cam, 0, 1)
    heat = Image.fromarray((np.stack([r, g, b], axis=-1) * 255).astype(np.uint8), mode="RGB").resize(image.size)
    labels = ["Atelectasis", "Cardiomegaly", "Effusion", "Infiltration", "Mass", "Nodule", "Pneumonia", "Pneumothorax", "Consolidation", "Edema", "Emphysema", "Fibrosis", "Pleural Thickening", "Hernia"]
    # These numbers are explicitly illustrative and must never be read as probabilities.
    scores = rng.uniform(0.08, 0.62, size=len(labels))
    scores[0] = min(0.72, 0.25 + contrast * 0.5)
    predictions = [{"label": label, "score": round(float(score), 6), "above_threshold": bool(score >= threshold)} for label, score in zip(labels, scores)]
    predictions.sort(key=lambda item: item["score"], reverse=True)
    return {
        "top_finding": predictions[0]["label"],
        "top_score": predictions[0]["score"],
        "threshold": threshold,
        "predictions": predictions,
        "gradcam": heat,
        "model_name": "DEMO MODE — simulated scores (no trained model)",
        "device": "CPU image-statistics demonstration",
        "mode": "demo_simulated",
        "explainability_type": "illustrative_image_map_not_gradcam",
        "notice": "SIMULATED DEMONSTRATION ONLY. These scores are not generated by a trained model, are not medical probabilities, and must not be used for diagnosis or patient care.",
    }


def _store_and_analyze(request: Request, content: bytes, filename: str, patient_ref: str, notes: str, source: str):
    model = request.app.state.model
    settings = request.app.state.settings
    try:
        image = image_from_bytes(content, filename)
    except ValueError as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc

    if model.is_ready:
        result = model.predict(image)
        result["mode"] = "trained_model"
        result["explainability_type"] = "gradcam"
    elif settings.demo_mode:
        result = _demo_analysis(image, settings.model_threshold)
    else:
        raise HTTPException(status_code=503, detail={
            "message": "The trained model is not available and demo mode is disabled.",
            "model_status": model.load_error,
            "next_step": "Train ml/train.py or enable DEMO_MODE for a clearly-labelled workflow demonstration.",
        })
    record_id = uuid4().hex
    storage = settings.resolved_storage_dir
    storage.mkdir(parents=True, exist_ok=True)
    original_name = f"{record_id}_original.png"
    heat_name = f"{record_id}_gradcam.png"
    overlay_name = f"{record_id}_overlay.png"
    save_preview(image, storage / original_name)
    result["gradcam"].save(storage / heat_name, format="PNG")
    overlay = Image.blend(image.convert("RGB"), result["gradcam"].convert("RGB"), alpha=0.38)
    overlay.save(storage / overlay_name, format="PNG")
    result.pop("gradcam", None)

    created = utc_now()
    study = {
        "id": record_id,
        "patient_ref": patient_ref.strip()[:80] or "UNASSIGNED",
        "notes": notes.strip()[:1000],
        "source": source,
        "original_filename": Path(filename).name[:255],
        "image_url": _media_url(original_name),
        "heatmap_url": _media_url(heat_name),
        "overlay_url": _media_url(overlay_name),
        "prediction": result,
        "review_status": "pending",
        "review": None,
        "created_at": created,
        "updated_at": created,
    }
    store = request.app.state.store
    saved = store.create_study(study)
    persisted_id = saved["id"]
    store.append_audit(persisted_id, {
        "action": "study_analyzed",
        "actor": "system",
        "details": {"source": source, "model_name": result["model_name"]},
        "created_at": created,
    })
    return saved


@router.get("/health")
def health(request: Request):
    model = request.app.state.model
    store = request.app.state.store
    return {
        "status": "ok",
        "model_loaded": model.is_ready,
        "demo_mode_enabled": bool(request.app.state.settings.demo_mode and not model.is_ready),
        "segmentation_model_loaded": request.app.state.segmentation_model.is_ready,
        "model_message": "Model ready" if model.is_ready else model.load_error,
        "segmentation_model_message": "3D segmentation model ready" if request.app.state.segmentation_model.is_ready else request.app.state.segmentation_model.load_error,
        "database": "mongodb" if store.persistent else "in-memory-fallback",
        "medical_notice": "Educational use only — not for clinical use.",
    }


@router.get("/studies")
def list_studies(request: Request, limit: int = 50):
    return request.app.state.store.list_studies(max(1, min(limit, 100)))


@router.post("/studies/upload")
async def upload_study(
    request: Request,
    file: UploadFile = File(...),
    patient_ref: str = Form(default="UNASSIGNED"),
    notes: str = Form(default=""),
):
    settings = request.app.state.settings
    content = await file.read(settings.max_upload_mb * 1024 * 1024 + 1)
    if len(content) > settings.max_upload_mb * 1024 * 1024:
        raise HTTPException(status_code=413, detail=f"File exceeds {settings.max_upload_mb} MB limit.")
    if not content:
        raise HTTPException(status_code=400, detail="The uploaded file is empty.")
    return _store_and_analyze(request, content, file.filename or "upload.png", patient_ref, notes, "upload")


@router.get("/studies/{study_id}")
def get_study(study_id: str, request: Request):
    study = request.app.state.store.get_study(study_id)
    if not study:
        raise HTTPException(status_code=404, detail="Study not found.")
    return study


@router.post("/studies/{study_id}/review")
def review_study(study_id: str, payload: ReviewPayload, request: Request):
    store = request.app.state.store
    if not store.get_study(study_id):
        raise HTTPException(status_code=404, detail="Study not found.")
    review = {
        "decision": payload.decision,
        "reviewer": payload.reviewer.strip(),
        "comments": payload.comments.strip(),
        "reviewed_at": utc_now(),
    }
    updated = store.update_review(study_id, review)
    store.append_audit(study_id, {
        "action": f"review_{payload.decision}",
        "actor": payload.reviewer.strip(),
        "details": {"comments": payload.comments.strip()},
        "created_at": review["reviewed_at"],
    })
    return updated


@router.get("/studies/{study_id}/audit")
def study_audit(study_id: str, request: Request):
    if not request.app.state.store.get_study(study_id):
        raise HTTPException(status_code=404, detail="Study not found.")
