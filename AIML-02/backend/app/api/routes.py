@router.post("/ct/segment")
async def segment_ct_volume(
    request: Request,
    file: UploadFile = File(...),
    patient_ref: str = Form(default="UNASSIGNED"),
    notes: str = Form(default=""),
):
    settings = request.app.state.settings
    content = await file.read(settings.max_volume_mb * 1024 * 1024 + 1)
    if len(content) > settings.max_volume_mb * 1024 * 1024:
        raise HTTPException(status_code=413, detail=f"Volume exceeds {settings.max_volume_mb} MB limit.")
    if not content:
        raise HTTPException(status_code=400, detail="The uploaded volume is empty.")
    segmentation_model = request.app.state.segmentation_model
    if not segmentation_model.is_ready:
        raise HTTPException(status_code=503, detail={
            "message": "The 3D segmentation checkpoint is not available yet.",
            "model_status": segmentation_model.load_error,
            "next_step": "Download Medical Segmentation Decathlon Task06_Lung and run ml/train_segmentation.py.",
        })
    try:
        result = segmentation_model.segment_nifti(content, file.filename or "ct-volume.nii.gz")
    except ValueError as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc
    except Exception as exc:
        raise HTTPException(status_code=500, detail=f"CT segmentation failed: {exc}") from exc

    record_id = uuid4().hex
    storage = settings.resolved_storage_dir
    storage.mkdir(parents=True, exist_ok=True)
    original_name = f"{record_id}_ct_slice.png"
    mask_name = f"{record_id}_mask.png"
    overlay_name = f"{record_id}_segmentation_overlay.png"
    save_preview(result["original_slice"], storage / original_name)
    save_preview(result["mask_slice"], storage / mask_name)
    save_preview(result["overlay_slice"], storage / overlay_name)
    result.pop("original_slice")
    result.pop("mask_slice")
    result.pop("overlay_slice")
    created = utc_now()
    study = {
        "id": record_id,
        "patient_ref": patient_ref.strip()[:80] or "UNASSIGNED",
        "notes": notes.strip()[:1000],
        "source": "nifti_upload",
        "modality": "CT",
        "original_filename": Path(file.filename or "ct-volume.nii.gz").name[:255],
        "image_url": _media_url(original_name),
        "heatmap_url": _media_url(mask_name),
        "overlay_url": _media_url(overlay_name),
        "prediction": {
            "task": "segmentation",
            "top_finding": "3D segmentation mask",
            "top_score": None,
            "predictions": [],
            "model_name": result["model_name"],
            "mask_voxels": result["mask_voxels"],
            "total_voxels": result["total_voxels"],
            "volume_shape": result["volume_shape"],
            "slice_index": result["slice_index"],
            "device": result["device"],
            "notice": result["notice"],
        },
        "review_status": "pending",
        "review": None,
        "created_at": created,
        "updated_at": created,
    }
    saved = request.app.state.store.create_study(study)
    request.app.state.store.append_audit(saved["id"], {
        "action": "ct_volume_segmented",
        "actor": "system",
        "details": {"model_name": result["model_name"], "slice_index": result["slice_index"]},
        "created_at": created,
    })
    return saved


@router.get("/orthanc/studies")
def orthanc_studies(request: Request):
    settings = request.app.state.settings
    client = OrthancClient(settings.orthanc_url, settings.orthanc_username, settings.orthanc_password)
    try:
        return client.list_studies()
    except Exception as exc:
        raise HTTPException(status_code=502, detail=f"Could not contact Orthanc: {exc}") from exc


@router.post("/orthanc/studies/{orthanc_id}/analyze")
def analyze_orthanc_study(orthanc_id: str, request: Request):
    settings = request.app.state.settings
    client = OrthancClient(settings.orthanc_url, settings.orthanc_username, settings.orthanc_password)
    try:
        content, filename = client.first_instance(orthanc_id)
    except ValueError as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc
    except Exception as exc:
        raise HTTPException(status_code=502, detail=f"Could not retrieve DICOM from Orthanc: {exc}") from exc
    return _store_and_analyze(request, content, filename, f"ORTHANC-{orthanc_id[:12]}", "Imported from Orthanc; first instance only in this MVP.", "orthanc")
