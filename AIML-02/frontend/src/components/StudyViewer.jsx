import React, { useState } from 'react';
import { Image as ImageIcon, Layers3, ScanEye } from 'lucide-react';
import StatusPill from './StatusPill';

function percent(value) { return `${(Number(value || 0) * 100).toFixed(1)}%`; }

export default function StudyViewer({ study, onReview, reviewBusy, audit }) {
  const [view, setView] = useState('overlay');
  const [reviewer, setReviewer] = useState('Radiology Reviewer');
  const [comments, setComments] = useState('');
  if (!study) return (
    <section className="empty-view card">
      <div className="empty-illustration"><ScanEye size={35} /></div>
      <h2>Your imaging workspace</h2>
      <p>Upload a de-identified chest X-ray to see model outputs, a Grad-CAM overlay, and the review workflow.</p>
      <div className="empty-steps"><span>01 <b>Upload scan</b></span><span>02 <b>Review AI output</b></span><span>03 <b>Record decision</b></span></div>
    </section>
  );

  const prediction = study.prediction || {};
  const isSegmentation = prediction.task === 'segmentation';
  const selectedImage = view === 'original' ? study.image_url : view === 'heatmap' ? study.heatmap_url : study.overlay_url;

  return (
    <div className="viewer-grid">
      <section className="card image-card">
        <div className="section-title-row">
          <div><span className="eyebrow">IMAGE REVIEW</span><h2>Study preview</h2></div>
          <StatusPill status={study.review_status} />
        </div>
        <div className="image-toolbar">
          <button className={view === 'original' ? 'view-tab active' : 'view-tab'} onClick={() => setView('original')}><ImageIcon size={15} /> Original</button>
          <button className={view === 'overlay' ? 'view-tab active' : 'view-tab'} onClick={() => setView('overlay')}><Layers3 size={15} /> Overlay</button>
          <button className={view === 'heatmap' ? 'view-tab active' : 'view-tab'} onClick={() => setView('heatmap')}><ScanEye size={15} /> Heatmap</button>
        </div>
        <div className="scan-stage">
          <img src={selectedImage} alt={`${view} medical scan preview`} />
          <span className="image-caption">{view === 'original' ? 'Original image / CT slice' : isSegmentation ? (view === 'overlay' ? '3D segmentation overlay · middle slice' : 'Segmentation mask · middle slice') : view === 'overlay' ? (prediction.mode === 'demo_simulated' ? 'Illustrative demo overlay · not Grad-CAM' : 'Grad-CAM overlay') : (prediction.mode === 'demo_simulated' ? 'Illustrative image map · not model explainability' : 'Grad-CAM activation map')}</span>
        </div>
        <div className="scan-meta">
          <div><span>STUDY REFERENCE</span><strong>{study.patient_ref}</strong></div>
          <div><span>UPLOADED</span><strong>{new Date(study.created_at).toLocaleString()}</strong></div>
          <div><span>INPUT FILE</span><strong>{study.original_filename}</strong></div>
        </div>
        <p className="image-disclaimer">{prediction.mode === 'demo_simulated' ? 'DEMO ONLY: this image map is illustrative and was not generated by a trained AI model. Demo scores are not medical probabilities.' : 'Grad-CAM is a coarse visualization of model sensitivity. It is not lesion segmentation and does not confirm a finding.'}</p>
      </section>

      <section className="card results-card">
        <div className="section-title-row"><div><span className="eyebrow">MODEL OUTPUT</span><h2>Finding scores</h2></div><span className="model-tag">{prediction.model_name || 'DenseNet121'}</span></div>
        {isSegmentation ? <>
          <div className="top-result">
            <div><span className="result-label">3D volume segmentation</span><h3>{prediction.top_finding || 'Segmentation mask'}</h3><small>Experimental mask · not a diagnosis</small></div>
            <strong>{Number(prediction.mask_voxels || 0).toLocaleString()}<small> voxels</small></strong>
          </div>
          <div className="segmentation-summary">
            <div><span>PROCESSED VOLUME</span><strong>{(prediction.volume_shape || []).join(' × ') || '—'}</strong></div>
            <div><span>MASK SLICE</span><strong>{prediction.slice_index ?? '—'}</strong></div>
            <div><span>MODEL</span><strong>MONAI 3D U-Net</strong></div>
          </div>
          <div className="threshold-note">Only the center axial slice is previewed here. The returned mask is an experimental segmentation, not a clinical contour.</div>
        </> : <>
          <div className="top-result">
            <div><span className="result-label">{prediction.mode === 'demo_simulated' ? 'Illustrative demo score' : 'Highest model score'}</span><h3>{prediction.top_finding || 'Not available'}</h3><small>{prediction.mode === 'demo_simulated' ? 'Simulated value · not a probability' : 'Experimental score · not a diagnosis'}</small></div>
            <strong>{percent(prediction.top_score)}</strong>
          </div>
          <div className="score-list">
            {(prediction.predictions || []).map((item) => (
              <div className="score-row" key={item.label}>
                <div className="score-copy"><span>{item.label}</span><strong>{percent(item.score)}</strong></div>
                <div className="score-track"><span style={{ width: `${Math.min(100, Math.max(0, item.score * 100))}%` }} /></div>
              </div>
            ))}
          </div>
          <div className="threshold-note">{prediction.mode === 'demo_simulated' ? 'Demo values only. Not AI predictions, not medical probabilities, and not for clinical interpretation.' : `Display threshold: ${(Number(prediction.threshold ?? 0.5) * 100).toFixed(0)}% · Scores are not calibrated clinical probabilities.`}</div>
        </>}
      </section>

      <section className="card review-card">
        <div className="section-title-row"><div><span className="eyebrow">HUMAN REVIEW</span><h2>Reviewer decision</h2></div><span className="review-lock">Doctor-led</span></div>
        {study.review ? <div className={`review-complete ${study.review.decision}`}>
          <strong>{study.review.decision === 'approved' ? 'Review approved' : 'Review rejected'}</strong>
          <span>Recorded by {study.review.reviewer} · {new Date(study.review.reviewed_at).toLocaleString()}</span>
          {study.review.comments && <p>{study.review.comments}</p>}
        </div> : <>
          <p className="review-hint">Review the scan and model output independently. Record your assessment below.</p>
          <label className="field-label">Reviewer name</label>
          <input className="text-input" value={reviewer} onChange={(e) => setReviewer(e.target.value)} maxLength={80} />
          <label className="field-label">Review comments <span>Optional</span></label>
          <textarea className="text-input review-textarea" value={comments} onChange={(e) => setComments(e.target.value)} maxLength={2000} placeholder="Document the review context..." />
          <div className="review-actions">
            <button className="reject-button" disabled={reviewBusy || reviewer.trim().length < 2} onClick={() => onReview('rejected', reviewer, comments)}>Reject output</button>
            <button className="approve-button" disabled={reviewBusy || reviewer.trim().length < 2} onClick={() => onReview('approved', reviewer, comments)}>Approve review</button>
          </div>
          <small className="demo-note">Demo workflow only. Reviewer identity is not authenticated.</small>
        </>}
      </section>

      <section className="card audit-card">
        <div className="section-title-row"><div><span className="eyebrow">TRACEABILITY</span><h2>Audit history</h2></div><span className="audit-count">{audit.length} events</span></div>
        {audit.length ? <div className="audit-list">{audit.map((event, index) => (
          <div className="audit-event" key={`${event.created_at}-${index}`}><span className="audit-dot" /><div><strong>{(event.action || 'event').replaceAll('_', ' ')}</strong><small>{event.actor || 'system'} · {new Date(event.created_at).toLocaleString()}</small>{event.details?.comments && <p>{event.details.comments}</p>}</div></div>
        ))}</div> : <p className="muted">No audit events recorded.</p>}
      </section>
    </div>
  );
}
